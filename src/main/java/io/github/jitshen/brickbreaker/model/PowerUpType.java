package io.github.jitshen.brickbreaker.model;

/** Kinds of power-up that can drop from destroyed bricks. */
public enum PowerUpType {
    /** Wider paddle for a while. */
    WIDE_PADDLE,
    /** Two extra balls. */
    MULTI_BALL,
    /** Balls move slower for a while. */
    SLOW_BALL,
    /** One more life, up to the maximum. */
    EXTRA_LIFE
}
